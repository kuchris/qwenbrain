"""Frozen/oracle/retrieval comparison for changes, history and unknown facts."""

import argparse
import json
import os
import subprocess
import sys
import time

from .paths import ROOT, configure_storage

configure_storage()

from .chat import ChatSession
from .check_update import parameter_hash
from .experiment_acquisition import normalize
from .experiment_memory import MemoryExperiment, file_hash
from .memory import VersionedMemoryStore


class TemporalExperiment(MemoryExperiment):
    """Reuse only the measured fresh-context generator and JSON report writer."""

    store_class = VersionedMemoryStore
    arms = ("F", "O", "R")

    def __init__(self, evidence_format="raw", *, config_path="configs/temporal-memory.json", run_prefix="temporal-memory"):
        self.evidence_format = evidence_format
        self.config = json.loads((ROOT / config_path).read_text(encoding="utf-8"))
        self.out = ROOT / "runs" / f"{run_prefix}-{time.time_ns()}"
        self.out.mkdir()
        self.session = ChatSession()
        self.model = self.session.model
        self.base_parameters = list(self.model.named_parameters())
        self.base_hash = parameter_hash(self.base_parameters)
        self.records = {r["id"]: r for r in self.config["records"]}
        self.live_path = ROOT / "adapters/live.safetensors"
        self.live_before = file_hash(self.live_path) if self.live_path.exists() else None
        paths = [config_path, "configs/chat.json", "qwenbrain/memory.py",
                 "qwenbrain/experiment_temporal_memory.py", "qwenbrain/experiment_memory.py",
                 "qwenbrain/experiment_acquisition.py", "qwenbrain/chat.py", "uv.lock"]
        self.report = {"protocol": self.config, "status": "running", "model": self.session.metadata,
                       "evidence_format": evidence_format,
                       "directory": self.out.relative_to(ROOT).as_posix(), "phases": [],
                       "base_sha256_before": self.base_hash,
                       "source_sha256": {p: file_hash(ROOT / p) for p in paths},
                       "scope": "Eight fresh synthetic identities; structured dates, one relation, whole-name lookup; no parameter updates. Explicit UNKNOWN instruction is shared across all arms. UNKNOWN is generated by the model, not returned directly by application logic.",
                       "time_semantics": "Latest effective state at requested date, using observations available by known_at. Later observations replace same-effective-date claims. Future queries abstain. This is retrospective corrected history, not a natural-language what-did-we-believe parser."}
        self.write()

    def generate(self, question, evidence):
        presented = evidence
        if self.evidence_format == "explicit":
            if evidence:
                record = evidence[0]
                content = (
                    "Memory lookup result: one project-name record selected for this person's requested date.\n"
                    "Project-name states remain valid until superseded. The database has already filtered dates and corrections.\n"
                    f"Source {record['id']}; effective from {record['valid_from']}; received {record['recorded_at']}.\n"
                    + record["content"] + "\nThis record supplies only a project name, not other personal attributes."
                )
            else:
                content = "Memory lookup result: EMPTY. No personal information supporting this question was found."
            presented = [{"content": content}]
        result = super().generate(question, presented)
        result["presented_memory"] = presented[0]["content"] if presented else None
        return result

    def questions(self, phase):
        rows = []

        def add(category, question, source_id=None):
            rows.append({"category": category, "question": question, "gold_source_id": source_id,
                         "expected": self.records[source_id]["value"] if source_id else "UNKNOWN"})

        for subject, source_id in zip(self.config["subjects"], phase["current_ids"]):
            add("current", f"Which project belongs to {subject} now? Reply with only its name or UNKNOWN.", source_id)
            add("current", f"Give the current name of {subject}'s project. Reply with only its name or UNKNOWN.", source_id)
        if phase["historical_ids"]:
            for subject, source_id in zip(self.config["subjects"], phase["historical_ids"]):
                add("history", f"On {self.config['historical_date']}, what was {subject}'s project named? Reply with only its name or UNKNOWN.", source_id)
        for subject in self.config["unknown_subjects"]:
            add("unknown_person", f"What is {subject}'s project called? Reply with only its name or UNKNOWN.")
        for subject in self.config["subjects"][:2]:
            add("before_first_record", f"On {self.config['before_date']}, what was {subject}'s project named? Reply with only its name or UNKNOWN.")
            add("future", f"On {self.config['future_date']}, what will {subject}'s project be named? Reply with only its name or UNKNOWN.")
            add("unsupported_attribute", f"What is {subject}'s favorite color? Reply with only the color or UNKNOWN.")
        for first, second in zip(self.config["subjects"][:2], self.config["subjects"][2:4]):
            add("ambiguous", f"Which project belongs to {first} or {second}? Reply with only one name if uniquely established, otherwise UNKNOWN.")
        rows += [{"category": "control", "question": r["question"], "expected": r["answer"],
                  "gold_source_id": None} for r in self.config["controls"]]
        return rows

    def evaluate_phase(self, arm, phase):
        answers = []
        questions = self.questions(phase)
        for index, item in enumerate(questions):
            started = time.perf_counter()
            if arm == "R":
                evidence = self.store.retrieve(item["question"], phase["known_at"])
            elif arm == "O" and item["gold_source_id"] is not None:
                r = self.records[item["gold_source_id"]]
                assert r["recorded_at"] <= phase["known_at"]
                evidence = [{k: r[k] for k in ("id", "content", "valid_from", "recorded_at")}]
            else:
                evidence = []
            result = self.generate(item["question"], evidence)
            result["query_seconds"] = time.perf_counter() - started
            exact = normalize(result["answer"]) == normalize(item["expected"])
            answers.append({**item, **result, "evidence": evidence, "exact_match": exact,
                            "exact_and_stopped": exact and result["ended_with_end_token"],
                            "answered_unknown": normalize(result["answer"]) == "unknown"})
            if (index + 1) % 16 == 0:
                print(phase["name"], arm, index + 1, "/", len(questions), flush=True)
        categories = {}
        for category in dict.fromkeys(a["category"] for a in answers):
            selected = [a for a in answers if a["category"] == category]
            categories[category] = {"correct": sum(a["exact_match"] for a in selected), "total": len(selected),
                                    "exact_and_stopped": sum(a["exact_and_stopped"] for a in selected)}
        known = [a for a in answers if a["gold_source_id"] is not None]
        unknown = [a for a in answers if a["expected"] == "UNKNOWN"]
        result = {"answers": answers, "categories": categories,
                  "known_correct": sum(a["exact_match"] for a in known), "known_total": len(known),
                  "unknown_correct": sum(a["exact_match"] for a in unknown), "unknown_total": len(unknown),
                  "false_abstentions": sum(a["answered_unknown"] for a in known),
                  "evidence_on_unknown_questions": sum(bool(a["evidence"]) for a in unknown),
                  "mean_query_seconds": sum(a["query_seconds"] for a in answers) / len(answers)}
        if arm in ("R", "O"):
            result["correct_source_selections"] = sum(bool(a["evidence"]) and a["evidence"][0]["id"] == a["gold_source_id"] for a in known)
        print(phase["name"], arm, "known", result["known_correct"], "/", len(known),
              "unknown", result["unknown_correct"], "/", len(unknown), flush=True)
        return result

    def verify_in_new_process(self, path):
        requests, expected = [], []
        for phase in self.report["phases"]:
            for answer in phase["arms"]["R"]["answers"]:
                requests.append({"question": answer["question"], "known_at": phase["known_at"]})
                expected.append(answer["evidence"])
        request_path = self.out / "restart-queries.json"
        response_path = self.out / "restart-evidence.json"
        request_path.write_text(json.dumps(requests), encoding="utf-8")
        code = (
            f"import json,sys; from pathlib import Path; from qwenbrain.memory import {self.store_class.__name__}; "
            f"store={self.store_class.__name__}(sys.argv[1]); "
            "queries=json.loads(Path(sys.argv[2]).read_text()); "
            "results=[store.retrieve(q['question'],q['known_at']) for q in queries]; "
            "store.close(); Path(sys.argv[3]).write_text(json.dumps(results),encoding='utf-8')"
        )
        subprocess.run([sys.executable, "-X", "utf8", "-c", code, str(path), str(request_path), str(response_path)],
                       check=True, cwd=ROOT, creationflags=subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0)
        assert json.loads(response_path.read_text()) == expected
        self.report["separate_process_all_retrievals_match"] = True
        self.report["separate_process_query_count"] = len(requests)

    def run(self):
        path = self.out / "temporal-memory.sqlite"
        self.store = self.store_class(path)
        written = set()
        for phase in self.config["phases"]:
            pending = [r for r in self.records.values() if r["recorded_at"] <= phase["known_at"] and r["id"] not in written]
            started = time.perf_counter()
            self.store.append(pending)
            self.store.close()
            write_seconds = time.perf_counter() - started
            written.update(r["id"] for r in pending)
            before = file_hash(path)
            self.store = self.store_class(path)
            self.session.messages = [{"role": "system", "content": self.config["system_prompt"] + " Today is " + phase["known_at"] + "."}]
            if not self.report["phases"]:
                self.generate("What is 2 + 2? Reply with only the number.", [])
            entry = {"name": phase["name"], "known_at": phase["known_at"], "written_source_ids": sorted(written),
                     "write_seconds": write_seconds, "sqlite_sha256_before_evaluation": before, "arms": {}}
            self.report["phases"].append(entry)
            self.write()
            for arm in self.arms:
                entry["arms"][arm] = self.evaluate_phase(arm, phase)
                self.write()
            self.store.close()
            entry["sqlite_sha256_after_evaluation"] = file_hash(path)
            assert before == entry["sqlite_sha256_after_evaluation"]
            self.store = self.store_class(path)
        self.store.close()
        before = file_hash(path)
        self.verify_in_new_process(path)
        assert file_hash(path) == before
        self.report["sqlite_bytes"] = path.stat().st_size
        self.report["base_sha256_after"] = parameter_hash(self.base_parameters)
        assert self.report["base_sha256_after"] == self.base_hash
        assert (file_hash(self.live_path) if self.live_path.exists() else None) == self.live_before
        self.report["live_checkpoint_unchanged"] = True
        for p, sha in self.report["source_sha256"].items():
            assert file_hash(ROOT / p) == sha
        self.report["status"] = "completed"
        self.write()
        print("RESULTS", self.out, flush=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--evidence-format", choices=("raw", "explicit"), default="raw")
    TemporalExperiment(parser.parse_args().evidence_format).run()
